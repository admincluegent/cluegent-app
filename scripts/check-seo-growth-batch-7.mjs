import assert from "node:assert/strict";
import { readFileSync, existsSync, readdirSync } from "node:fs";
import { growthPostsBatch7, growthBacklinksBatch7 } from "./seo-growth-posts-batch-7.mjs";
import { growthPostsBatch8, growthBacklinksBatch8 } from "./seo-growth-posts-batch-8.mjs";
import { competitorPostsBatch9, competitorBacklinksBatch9 } from "./seo-competitor-posts-batch-9.mjs";
const batch8 = process.argv.includes("--batch8");
const batch9 = process.argv.includes("--batch9");
const posts = batch9 ? competitorPostsBatch9 : batch8 ? growthPostsBatch8 : growthPostsBatch7;
const backlinks = batch9 ? competitorBacklinksBatch9 : batch8 ? growthBacklinksBatch8 : growthBacklinksBatch7;
const batch8Parents = new Set([...growthBacklinksBatch8, ...competitorBacklinksBatch9].map(([slug])=>slug));
const root = new URL("../website/", import.meta.url);
const read = path => readFileSync(new URL(path, root), "utf8");
const hub = read("blog/index.html");
const sitemap = read("sitemap.xml");
assert.equal(posts.length, batch9 ? 10 : 20);
assert.equal(new Set(posts.map(p => p.slug)).size, posts.length);
assert.equal(new Set(posts.map(p => p.title)).size, posts.length);
const sitemapUrls = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map(m=>m[1]);
assert.equal(new Set(sitemapUrls).size, sitemapUrls.length, "duplicate sitemap URL");
let minimumWords = Infinity;
for (const p of posts) {
  const url = `https://www.cluegent.com/blog/${p.slug}/`;
  const html = read(`blog/${p.slug}/index.html`);
  assert.equal((html.match(/<h1[ >]/g)||[]).length, 1, p.slug);
  assert(html.includes(`rel="canonical" href="${url}"`), p.slug);
  assert(!/noindex/i.test(html), p.slug);
  assert(hub.includes(`href="/blog/${p.slug}/"`), p.slug);
  const modifiedDate = batch8Parents.has(p.slug) ? "2026-10-05" : p.modifiedDate;
  assert(sitemap.includes(`<loc>${url}</loc><lastmod>${modifiedDate}</lastmod>`), p.slug);
  const schemas = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)].flatMap(m=>JSON.parse(m[1]));
  const article = schemas.find(s=>s["@type"] === "Article");
  assert.equal(article.mainEntityOfPage, url);
  assert.equal(article.datePublished, p.publishedDate);
  assert.equal(article.dateModified, modifiedDate);
  assert.equal(schemas.find(s=>s["@type"] === "FAQPage").mainEntity.length, p.faqs.length);
  const words = p.bodyHtml.replace(/<[^>]+>/g, " ").trim().split(/\s+/).length;
  minimumWords = Math.min(minimumWords, words);
  assert(words >= 500, `${p.slug}: ${words} words`);
  assert(!/\b(TODO|TBD|lorem ipsum)\b/i.test(p.bodyHtml));
  for (const [, href] of html.matchAll(/href="(\/[^"?#]*)/g)) assert(existsSync(new URL(href.slice(1)+(href.endsWith("/")?"index.html":""),root)),`${p.slug}: ${href}`);
}
for(const [parent,slug] of backlinks) assert(read(`blog/${parent}/index.html`).includes(`href="/blog/${slug}/"`),`${parent} -> ${slug}`);
const titles = readdirSync(new URL("blog/",root),{withFileTypes:true}).filter(d=>d.isDirectory()).map(d=>read(`blog/${d.name}/index.html`).match(/<title>(.*?)<\/title>/)?.[1]);
for(const p of posts) assert.equal(titles.filter(t=>t===p.title).length,1,p.title);
assert.equal(300+20*2+2,342);
assert.equal(100/1000*100,10);
assert.equal(120/1000*100,12);
assert.equal((12-10)/10*100,20);
assert.equal(10+20,30);
assert.equal((10+20)*2,60);
assert.equal((10+20)*3,90);
console.log(JSON.stringify({passed:true,articles:posts.length,minimumWords,sitemapUrls:sitemapUrls.length,checks:"unique titles, metadata, canonicals, structured data, sitemap, links and worked examples"}));
